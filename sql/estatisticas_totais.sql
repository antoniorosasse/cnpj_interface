--
-- Recriacao da estrutura de estatisticas do bancocnpj SEM o TRUNCATE que
-- travava a pagina /estatisticas/ durante os ~401 s do recalculo.
--
-- Como funciona:
--   1. A procedure calcula tudo em c_estatisticas_calc (tabela de rascunho).
--      A tabela publica c_estatisticas_totais fica intocada e continua
--      servindo o site (SELECT em < 5 ms) durante todo o calculo.
--   2. No fim, dentro da MESMA transacao, as duas tabelas trocam de nome
--      (ALTER TABLE ... RENAME). O lock exclusivo da tabela publica existe
--      apenas por alguns milissegundos, na troca - nao pelos 11 minutos.
--   3. A tabela antiga e dropada no fim (a sequence e os indices dela vao
--      junto). Sequence e indices da tabela nova sao renomeados para os
--      nomes historicos (c_estatisticas_totais_id_seq,
--      c_estatisticas_totais_pkey, uq_estatisticas_origem_cat_chave).
--
-- c_estatisticas_recalculo guarda o status do ultimo recalculo (1 linha) para
-- a pagina mostrar "recalculando..." e para o botao nao disparar duas vezes.
--
-- Aplicar (idempotente, nao apaga a tabela publica):
--   psql -U arosasse -d bancocnpj -f sql/estatisticas_totais.sql
-- Rodar o recalculo fora do request:
--   python manage.py recalcular_totais          (~11 min na base de 74,4 M)
--   python manage.py recalcular_totais --status

BEGIN;

-- ===========================================================================
-- 1. Status do recalculo (linha unica)
-- ===========================================================================
CREATE TABLE IF NOT EXISTS c_estatisticas_recalculo (
    id           smallint     PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    status       varchar(20)  NOT NULL DEFAULT 'nunca',  -- nunca|rodando|ok|erro
    iniciado_em  timestamptz,
    terminado_em timestamptz,
    duracao_s    numeric(10, 2),
    linhas       integer,
    pid          integer,
    mensagem     text
);

INSERT INTO c_estatisticas_recalculo (id, status)
VALUES (1, 'nunca')
ON CONFLICT (id) DO NOTHING;

-- ===========================================================================
-- 2. Procedure de recalculo com troca de tabela
-- ===========================================================================
CREATE OR REPLACE PROCEDURE public.sp_recalcular_estatisticas_totais()
 LANGUAGE plpgsql
AS $procedure$
BEGIN
    -- Resto de uma execucao interrompida por fora (nao deve existir: o swap
    -- inteiro roda numa transacao).
    DROP TABLE IF EXISTS c_estatisticas_antiga;

    -- Rascunho: criado na primeira execucao; depois so e limpo. A tabela
    -- publica NAO e tocada aqui.
    CREATE TABLE IF NOT EXISTS c_estatisticas_calc (
        id             integer GENERATED BY DEFAULT AS IDENTITY,
        tabelas_origem varchar(100) NOT NULL,
        categoria      varchar(50)  NOT NULL,
        chave          varchar(100) NOT NULL,
        descricao      varchar(255),
        valor          bigint       NOT NULL,
        atualizado_em  timestamptz  DEFAULT now(),
        CONSTRAINT c_estatisticas_calc_pkey PRIMARY KEY (id),
        CONSTRAINT uq_estatisticas_calc_origem_cat_chave UNIQUE (tabelas_origem, categoria, chave)
    );

    TRUNCATE TABLE c_estatisticas_calc RESTART IDENTITY;

    -- 1. Total Geral de Matrizes
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT 'c_estabelecimentos', 'geral', 'total_matrizes', 'Total de matrizes', COUNT(*)
    FROM c_estabelecimentos
    WHERE cd_matriz_filial = 1;

    -- 2. Situacoes Cadastrais
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos',
        'situacao',
        CASE
            WHEN cd_sit_cadastro = 1 THEN 'NULA'
            WHEN cd_sit_cadastro = 2 THEN 'ATIVA'
            WHEN cd_sit_cadastro = 3 THEN 'SUSPENSA'
            WHEN cd_sit_cadastro = 4 THEN 'INAPTA'
            WHEN cd_sit_cadastro = 8 THEN 'BAIXADA'
            ELSE 'OUTRA'
        END,
        'Matrizes na situacao ' ||
        CASE
            WHEN cd_sit_cadastro = 1 THEN 'NULA'
            WHEN cd_sit_cadastro = 2 THEN 'ATIVA'
            WHEN cd_sit_cadastro = 3 THEN 'SUSPENSA'
            WHEN cd_sit_cadastro = 4 THEN 'INAPTA'
            WHEN cd_sit_cadastro = 8 THEN 'BAIXADA'
            ELSE 'OUTRA'
        END,
        COUNT(*)
    FROM c_estabelecimentos
    WHERE cd_matriz_filial = 1
    GROUP BY cd_sit_cadastro;

    -- 3. UFs (todas as 27 UFs)
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos',
        'uf',
        UPPER(uf),
        'Matrizes na UF ' || UPPER(uf),
        COUNT(*)
    FROM c_estabelecimentos
    WHERE cd_matriz_filial = 1 AND uf IS NOT NULL AND TRIM(uf) <> ''
    GROUP BY UPPER(uf);

    -- 3b. UF + situacao ATIVA (responde "quantas empresas ativas por UF").
    -- Medido em 28/11/2026: ~25 s nesta varredura; o chat respondia em ~26 s
    -- ou recusava. A categoria deixa a leitura em milissegundos.
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos',
        'uf_ativa',
        UPPER(uf),
        'Matrizes ativas na UF ' || UPPER(uf),
        COUNT(*)
    FROM c_estabelecimentos
    WHERE cd_matriz_filial = 1 AND cd_sit_cadastro = 2
      AND uf IS NOT NULL AND TRIM(uf) <> ''
    GROUP BY UPPER(uf);

    -- 3c. Municipio + situacao ATIVA (responde "ativas por UF e cidade").
    -- A chave leva a UF: 'SC|8105'. Custo medido: ~30 s para o Brasil todo.
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    WITH t AS (
        -- Agrupa pelo codigo antes de juntar o nome: juntar c_municipios
        -- antes do GROUP BY levava > 5 min no Brasil todo.
        SELECT UPPER(uf) AS uf, municipio, COUNT(*) AS valor
        FROM c_estabelecimentos
        WHERE cd_matriz_filial = 1 AND cd_sit_cadastro = 2
          AND uf IS NOT NULL AND municipio IS NOT NULL
        GROUP BY UPPER(uf), municipio
    )
    SELECT
        'c_estabelecimentos + c_municipios',
        'municipio_ativa',
        t.uf || '|' || t.municipio::text,
        COALESCE(m.municipio, 'NAO INFORMADO') || '|' || t.uf,
        t.valor
    FROM t
    LEFT JOIN c_municipios m ON m.cd_municipio = t.municipio;

    -- 3d. UF + ano de abertura + situacao ATIVA (responde "ativas por ano
    -- em SC"): a consulta direta levava ~68 s e era recusada. Chave
    -- 'SC|2025'.
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos',
        'uf_ano_ativa',
        UPPER(uf) || '|' || EXTRACT(YEAR FROM dt_ini)::integer::text,
        'Ativas abertas em ' || EXTRACT(YEAR FROM dt_ini)::integer::text
            || ' na UF ' || UPPER(uf),
        COUNT(*)
    FROM c_estabelecimentos
    WHERE cd_matriz_filial = 1 AND cd_sit_cadastro = 2
      AND uf IS NOT NULL AND TRIM(uf) <> '' AND dt_ini IS NOT NULL
    GROUP BY UPPER(uf), EXTRACT(YEAR FROM dt_ini);

    -- 3e. Capitais + situacao ATIVA (responde "ativas por UF e capitais").
    -- Codigos TOM (c_municipios.cd_municipio), um por UF; nao depende de
    -- c_municipios_geo, que ainda nao existe em producao.
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos + c_municipios',
        'capital_ativa',
        split_part(chave, '|', 1),
        'Matrizes ativas na capital ' || descricao,
        valor
    FROM c_estatisticas_calc
    WHERE categoria = 'municipio_ativa'
      AND chave IN (
        'AC|139', 'AL|2785', 'AM|255', 'AP|605', 'BA|3849', 'CE|1389',
        'DF|9701', 'ES|5705', 'GO|9373', 'MA|921', 'MG|4123', 'MS|9051',
        'MT|9067', 'PA|427', 'PB|2051', 'PE|2531', 'PI|1219', 'PR|7535',
        'RJ|6001', 'RN|1761', 'RO|3', 'RR|301', 'RS|8801', 'SC|8105',
        'SE|3105', 'SP|7107', 'TO|9733'
      );

    -- 3f. Niveis de filtro da pagina de estatisticas (UF, cidade, CNAE,
    -- situacao e porte). Sao lidos em milissegundos pela pagina; sem eles
    -- qualquer filtro exigiria varrer os 74,4 M de estabelecimentos.
    --
    -- UF + situacao + porte (para os KPIs e distribuicoes de porte/situacao)
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos + c_empresas',
        'filtro_uf_sit_porte',
        UPPER(e.uf) || '|' || e.cd_sit_cadastro::text || '|' ||
        CASE
            WHEN emp.porte_empresa = 1 THEN '1'
            WHEN emp.porte_empresa = 3 THEN '3'
            WHEN emp.porte_empresa = 5 THEN '5'
            ELSE '0'
        END,
        'UF ' || UPPER(e.uf) || ' situacao ' || e.cd_sit_cadastro::text,
        COUNT(*)
    FROM c_estabelecimentos e
    JOIN c_empresas emp ON emp.cnpj_basico = e.cnpj_basico
    WHERE e.cd_matriz_filial = 1
      AND e.uf IS NOT NULL AND TRIM(e.uf) <> ''
    GROUP BY UPPER(e.uf), e.cd_sit_cadastro,
        CASE
            WHEN emp.porte_empresa = 1 THEN '1'
            WHEN emp.porte_empresa = 3 THEN '3'
            WHEN emp.porte_empresa = 5 THEN '5'
            ELSE '0'
        END;

    -- UF + municipio + situacao + porte (filtro de cidade e porte)
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    WITH t AS (
        SELECT UPPER(e.uf) AS uf, e.municipio, e.cd_sit_cadastro,
               CASE
                   WHEN emp.porte_empresa = 1 THEN '1'
                   WHEN emp.porte_empresa = 3 THEN '3'
                   WHEN emp.porte_empresa = 5 THEN '5'
                   ELSE '0'
               END AS porte,
               COUNT(*) AS valor
        FROM c_estabelecimentos e
        JOIN c_empresas emp ON emp.cnpj_basico = e.cnpj_basico
        WHERE e.cd_matriz_filial = 1
          AND e.uf IS NOT NULL AND e.municipio IS NOT NULL
        GROUP BY UPPER(e.uf), e.municipio, e.cd_sit_cadastro,
                 CASE
                     WHEN emp.porte_empresa = 1 THEN '1'
                     WHEN emp.porte_empresa = 3 THEN '3'
                     WHEN emp.porte_empresa = 5 THEN '5'
                     ELSE '0'
                 END
    )
    SELECT
        'c_estabelecimentos + c_empresas + c_municipios',
        'filtro_uf_mun_sit_porte',
        t.uf || '|' || t.municipio::text || '|' || t.cd_sit_cadastro::text
            || '|' || t.porte,
        COALESCE(m.municipio, 'NAO INFORMADO') || '|' || t.uf,
        t.valor
    FROM t
    LEFT JOIN c_municipios m ON m.cd_municipio = t.municipio;

    -- UF + CNAE + situacao + porte (filtro de atividade e porte)
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    WITH t AS (
        SELECT UPPER(e.uf) AS uf, e.cnae_principal AS cnae,
               e.cd_sit_cadastro,
               CASE
                   WHEN emp.porte_empresa = 1 THEN '1'
                   WHEN emp.porte_empresa = 3 THEN '3'
                   WHEN emp.porte_empresa = 5 THEN '5'
                   ELSE '0'
               END AS porte,
               COUNT(*) AS valor
        FROM c_estabelecimentos e
        JOIN c_empresas emp ON emp.cnpj_basico = e.cnpj_basico
        WHERE e.cd_matriz_filial = 1
          AND e.uf IS NOT NULL AND e.cnae_principal IS NOT NULL
        GROUP BY UPPER(e.uf), e.cnae_principal, e.cd_sit_cadastro,
                 CASE
                     WHEN emp.porte_empresa = 1 THEN '1'
                     WHEN emp.porte_empresa = 3 THEN '3'
                     WHEN emp.porte_empresa = 5 THEN '5'
                     ELSE '0'
                 END
    )
    SELECT
        'c_estabelecimentos + c_empresas + c_cnaes',
        'filtro_uf_cnae_sit_porte',
        t.uf || '|' || t.cnae::text || '|' || t.cd_sit_cadastro::text
            || '|' || t.porte,
        COALESCE(c.nm_cnae, 'NAO INFORMADO'),
        t.valor
    FROM t
    LEFT JOIN c_cnaes c ON c.cnae = t.cnae;

    -- UF + ano de abertura + situacao + porte (serie anual filtrada)
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    WITH t AS (
        SELECT UPPER(e.uf) AS uf, EXTRACT(YEAR FROM e.dt_ini)::integer AS ano,
               e.cd_sit_cadastro,
               CASE
                   WHEN emp.porte_empresa = 1 THEN '1'
                   WHEN emp.porte_empresa = 3 THEN '3'
                   WHEN emp.porte_empresa = 5 THEN '5'
                   ELSE '0'
               END AS porte,
               COUNT(*) AS valor
        FROM c_estabelecimentos e
        JOIN c_empresas emp ON emp.cnpj_basico = e.cnpj_basico
        WHERE e.cd_matriz_filial = 1
          AND e.uf IS NOT NULL AND e.dt_ini IS NOT NULL
        GROUP BY UPPER(e.uf), EXTRACT(YEAR FROM e.dt_ini), e.cd_sit_cadastro,
                 CASE
                     WHEN emp.porte_empresa = 1 THEN '1'
                     WHEN emp.porte_empresa = 3 THEN '3'
                     WHEN emp.porte_empresa = 5 THEN '5'
                     ELSE '0'
                 END
    )
    SELECT
        'c_estabelecimentos + c_empresas',
        'filtro_uf_ano_sit_porte',
        t.uf || '|' || t.ano::text || '|' || t.cd_sit_cadastro::text
            || '|' || t.porte,
        'Aberturas ' || t.ano::text || ' na UF ' || t.uf,
        t.valor
    FROM t;

    -- 4. Simples Nacional e MEI
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT 'c_simples', 'simples', 'S', 'Optantes pelo Simples Nacional', COUNT(*)
    FROM c_simples WHERE op_simples = 'S';

    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT 'c_simples', 'mei', 'S', 'Optantes pelo MEI', COUNT(*)
    FROM c_simples WHERE op_mei = 'S';

    -- 5. Portes da Empresa (com o nome exato esperado pelo template)
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_empresas',
        'porte',
        CASE
            WHEN porte_empresa = 1 THEN 'ME'
            WHEN porte_empresa = 3 THEN 'EPP'
            WHEN porte_empresa = 5 THEN 'DEMAIS'
            ELSE 'NAO_INFORMADO'
        END,
        CASE
            WHEN porte_empresa = 1 THEN 'MICRO EMPRESA'
            WHEN porte_empresa = 3 THEN 'EMPRESA DE PEQUENO PORTE'
            WHEN porte_empresa = 5 THEN 'DEMAIS'
            ELSE 'NÃO INFORMADO'
        END,
        COUNT(*)
    FROM c_empresas
    GROUP BY porte_empresa;

    -- 6. Top 15 CNAEs
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos + c_cnaes',
        'cnae',
        e.cnae_principal::text,
        COALESCE(c.nm_cnae, 'N/A'),
        COUNT(*)
    FROM c_estabelecimentos e
    LEFT JOIN c_cnaes c ON e.cnae_principal = c.cnae
    WHERE e.cd_matriz_filial = 1 AND e.cnae_principal IS NOT NULL
    GROUP BY e.cnae_principal, c.nm_cnae
    ORDER BY COUNT(*) DESC
    LIMIT 15;

    -- 7. Top 15 Naturezas Juridicas
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_empresas + c_naturezas',
        'natureza',
        emp.nat_juridica::text,
        COALESCE(n.nat_juridica, 'NÃO INFORMADA'),
        COUNT(*)
    FROM c_empresas emp
    LEFT JOIN c_naturezas n ON emp.nat_juridica = n.cd_nat_juridica
    WHERE emp.nat_juridica IS NOT NULL
    GROUP BY emp.nat_juridica, n.nat_juridica
    ORDER BY COUNT(*) DESC
    LIMIT 15;

    -- 8. Empresas por Ano de Abertura
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos',
        'ano',
        EXTRACT(YEAR FROM dt_ini)::integer::text,
        'Aberturas no ano ' || EXTRACT(YEAR FROM dt_ini)::integer::text,
        COUNT(*)
    FROM c_estabelecimentos
    WHERE cd_matriz_filial = 1
      AND dt_ini IS NOT NULL
      AND EXTRACT(YEAR FROM dt_ini) >= 2010
    GROUP BY EXTRACT(YEAR FROM dt_ini);

    -- 9. Top 15 Municipios
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT
        'c_estabelecimentos + c_municipios',
        'municipio',
        e.municipio::text,
        COALESCE(m.municipio, 'NÃO INFORMADO') || '|' || COALESCE(e.uf, ''),
        COUNT(*)
    FROM c_estabelecimentos e
    LEFT JOIN c_municipios m ON e.municipio = m.cd_municipio
    WHERE e.cd_matriz_filial = 1 AND e.municipio IS NOT NULL
    GROUP BY e.municipio, m.municipio, e.uf
    ORDER BY COUNT(*) DESC
    LIMIT 15;

    -- 10. Socios
    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT 'c_socios', 'socios', 'total_socios', 'Total de Sócios', COUNT(*)
    FROM c_socios;

    INSERT INTO c_estatisticas_calc (tabelas_origem, categoria, chave, descricao, valor)
    SELECT 'c_socios', 'socios', 'empresas_com_socios', 'Empresas com Sócios', COUNT(DISTINCT cnpj_basico)
    FROM c_socios;

    -- =======================================================================
    -- 11. Troca atomica (lock exclusivo por milissegundos, nao por 11 min)
    --     Em todo statement existe uma tabela chamada c_estatisticas_totais,
    --     para nao haver janela em que o nome nao resolva.
    -- =======================================================================
    LOCK TABLE c_estatisticas_totais IN ACCESS EXCLUSIVE MODE;

    ALTER TABLE c_estatisticas_totais RENAME TO c_estatisticas_antiga;
    ALTER SEQUENCE c_estatisticas_totais_id_seq RENAME TO c_estatisticas_antiga_id_seq;
    ALTER INDEX c_estatisticas_totais_pkey RENAME TO c_estatisticas_antiga_pkey;
    ALTER INDEX uq_estatisticas_origem_cat_chave RENAME TO uq_estatisticas_antiga_origem_cat_chave;

    ALTER TABLE c_estatisticas_calc RENAME TO c_estatisticas_totais;
    ALTER SEQUENCE c_estatisticas_calc_id_seq RENAME TO c_estatisticas_totais_id_seq;
    ALTER INDEX c_estatisticas_calc_pkey RENAME TO c_estatisticas_totais_pkey;
    ALTER INDEX uq_estatisticas_calc_origem_cat_chave RENAME TO uq_estatisticas_origem_cat_chave;

    -- Leva junto a sequence e os indices antigos (renomeados acima).
    DROP TABLE c_estatisticas_antiga;

    -- A tabela nova nasce sem os grants da antiga: o chat (role chat_ia) le
    -- c_estatisticas_totais via SELECT direto.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'chat_ia') THEN
        GRANT SELECT ON TABLE c_estatisticas_totais TO chat_ia;
    END IF;
END;
$procedure$;

-- ===========================================================================
-- 3. Permissao de leitura para o chat (idempotente)
-- ===========================================================================
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'chat_ia') THEN
        GRANT SELECT ON TABLE c_estatisticas_recalculo TO chat_ia;
    END IF;
END
$$;

COMMIT;
